/// One 32-byte range-reduction row of the log kernel's seed table.
/// A row matches u when `exp >= exponent(u)` and
/// `mant29(u) >> (exp - exponent(u)) < threshold`, i.e. when u is small
/// enough for the row's pre-rotation; rows are searched from 8 down to 0.
pub struct LogSeedEntry {
    /// Q29 acceptance bound on the row-aligned mantissa.
    pub threshold: i32,
    /// Largest input exponent the row serves.
    pub exp: i32,
    /// Q29 cosh-like pre-rotation coefficient (A).
    pub cosh_seed: i32,
    /// Q29 sinh-like pre-rotation coefficient (B, negative), applied as
    /// B * 2^-seed_shift.
    pub sinh_seed: i32,
    /// Binary point offset S of `sinh_seed`.
    pub seed_shift: i32,
    /// Initial atanh accumulator, in Q(30 + result_scale - 1).
    pub acc_seed: i32,
    /// Result fixed-point scale: acc is divided by 2^(30 + result_scale - 1).
    pub result_scale: i32,
    /// First CORDIC iteration index (into [`ATANH_TABLE`]).
    pub start_index: i32,
}

