/// ARM register-controlled ASR: only the low 8 bits of the shift count
/// participate, and counts >= 32 fill with the sign bit. The CORDIC
/// shift counters exceed 31 late in every 32-iteration run, so plain
/// Rust `>>` (UB/panic at 32) cannot be used.
#[inline]
fn arm_asr(value: i32, shift: i32) -> i32 {
    let s = (shift as u32) & 0xff;
    if s >= 32 {
        value >> 31
    } else {
        value >> s
    }
}

/// `i - (i >= 4) - (i >= 14)`: the effective shift index of CORDIC
/// iteration `i` once the repeated iterations 3 and 13 are discounted.
/// The original re-materializes this with cmp/movge chains at every use.
#[inline]
fn repeat_adjusted(i: i32) -> i32 {
    i - (i >= 4) as i32 - (i >= 14) as i32
}

/// log_atanh_kernel — original: `FUN_08035b3c` @ 0x08035b3c (524 bytes).
///
/// Fixed-point atanh: `u` is a float bit pattern, the result is
/// atanh(u) as a float bit pattern (see the module header). Inputs
/// <= 0x39800000 (2^-12; signed compare, so any negative bit pattern
/// too) return unchanged. Sole caller: `log_decompose` @ 0x080340fc via
/// the `LOG_ATANH_KERNEL` hook, which feeds u in [0, 0.6).
#[cfg_attr(target_os = "none", no_mangle)]
pub unsafe extern "C" fn log_atanh_kernel(u: u32) -> u32 {
    if (u as i32) <= 0x3980_0000 {
        return u;
    }
    let e = (((u << 1) >> 24) as i32).wrapping_sub(0x7f);
    // Q29 mantissa in [2^29, 2^30): implicit bit restored, << 6.
    let mant = (((u & 0x00ff_ffff) | 0x0080_0000) << 6) as i32;

    // Row search, 8 down to 0 (row 0 accepts everything below 1.0, so
    // the no-match defaults below are unreachable but kept faithful).
    let mut x: i32 = 0x2000_0000;
    let mut y: i32 = mant;
    let mut acc: i32 = 0;
    let mut scale_log2: i32 = 0;
    let mut i: i32 = 0;
    let mut min_shift: i32 = 0;
    for row in LOG_SEED_TABLE.iter().rev() {
        if row.exp >= e && row.threshold.wrapping_sub(arm_asr(mant, row.exp - e)) > 0 {
            // Pre-rotation in 64-bit Q58: x = A + u*B*2^-S,
            // y = u*A + B*2^-S, both taken >> 29 back to Q29. The lasr
            // shift splits differ so every operand stays in range.
            min_shift = if row.seed_shift > -e { -e } else { row.seed_shift };
            let x64 = (0x2000_0000i64 * row.cosh_seed as i64).wrapping_add(__aeabi_lasr(
                mant as i64 * row.sinh_seed as i64,
                (row.seed_shift - e) as u32,
            ));
            let y64 = __aeabi_lasr(
                mant as i64 * row.cosh_seed as i64,
                (-(e + min_shift)) as u32,
            )
            .wrapping_add(__aeabi_lasr(
                0x2000_0000i64 * row.sinh_seed as i64,
                (row.seed_shift - min_shift) as u32,
            ));
            x = (x64 >> 29) as i32;
            y = (y64 >> 29) as i32;
            acc = row.acc_seed;
            scale_log2 = row.result_scale - 1;
            i = row.start_index;
            break;
        }
    }

    // 32 vectoring iterations: drive y -> 0, gather atanh terms.
    let adj = repeat_adjusted(i);
    let mut sh_y = adj + min_shift + 1;
    let mut sh_x = adj - min_shift + 1;
    let mut sh_t = adj - scale_log2 + 1;
    for _ in 0..32 {
        // Reachable i stays within 0..=40 (start_index <= 9 + 31
        // iterations); the original indexes unchecked.
        let t = arm_asr(*ATANH_TABLE.get_unchecked(i as usize), sh_t);
        let dy = arm_asr(y, sh_y);
        let dx = arm_asr(x, sh_x);
        if y >= 0 {
            x = x.wrapping_sub(dy);
            acc = acc.wrapping_add(t);
            y = y.wrapping_sub(dx);
        } else {
            x = dy.wrapping_add(x);
            y = y.wrapping_add(dx);
            acc = acc.wrapping_sub(t);
        }
        if i != 3 && i != 13 {
            sh_y += 1;
            sh_x += 1;
            sh_t += 1;
        }
        i += 1;
    }

    // acc / 2^(30 + scale_log2), via __i2f / __fscalb / __fdiv exactly as
    // the original tail (scale_log2 <= 12, so 1 << scale_log2 is exact).
    let divisor = __fscalb(__i2f(1i32.wrapping_shl(scale_log2 as u32)), 30);
    __fdiv(__i2f(acc), divisor)
}

/// exp_frac_kernel — original: `FUN_08035d50` @ 0x08035d50 (696 bytes).
///
/// Fixed-point e^frac (see the module header): writes sinh(frac) /
/// cosh(frac) / e^frac float bit patterns through the three out
/// pointers; the sole caller (`expf_core` @ 0x08033f40 via the
/// `EXP_FRAC_KERNEL` hook) reads only `*out_result`. `frac` <= 2^-12
/// (signed compare) short-cuts to (frac, 1.0f, frac + 1.0f).
#[cfg_attr(target_os = "none", no_mangle)]
pub unsafe extern "C" fn exp_frac_kernel(
    frac: u32,
    out_sinh: *mut u32,
    out_cosh: *mut u32,
    out_result: *mut u32,
) {
    if (frac as i32) <= 0x3980_0000 {
        *out_sinh = frac;
        *out_cosh = ONE_F;
        *out_result = __fadd(frac, ONE_F);
        return;
    }
    let e = (((frac << 1) >> 24) as i32).wrapping_sub(0x7f);
    let mant = (((frac & 0x00ff_ffff) | 0x0080_0000) << 6) as i32;

    let mut x: i32 = 0x2000_0000;
    let mut y: i32 = 0;
    let n: i32;
    let mut z: i32;
    if e >= 0 {
        // Unreachable from the sole caller (frac < 1.0); kept faithful:
        // no seed subtraction, the raw Q29 mantissa is the angle.
        n = 0;
        z = mant;
    } else {
        // Exponent in [-12, -1] on the main path (the fast path consumed
        // everything below); the original indexes unchecked.
        let seed = EXP_SEED_TABLE.get_unchecked((-e - 1) as usize);
        n = seed.start_index;
        z = mant.wrapping_sub(seed.atanh_sum);
        // Align the residual to the main loop's fixed point.
        let s = repeat_adjusted(n) + e + 1;
        if s > 0 {
            z = z.wrapping_shl(s as u32);
        } else if s < 0 {
            z = arm_asr(z, -s);
        }
        // Seed rotations 0..n: fixed directions (negative at i = 0 and
        // i = 7, the (1 << i) & 0x81 test), y doubling each non-repeat
        // step to track the shrinking rotation scale.
        let mut shift: i32 = 1;
        for i in 0..n {
            let negative = (1i32.wrapping_shl(i as u32)) & 0x81 != 0;
            let dy = arm_asr(y, shift);
            let (xn, yn) = if negative {
                (dy.wrapping_add(x), y.wrapping_add(arm_asr(x, 1)))
            } else {
                (x.wrapping_sub(dy), y.wrapping_sub(arm_asr(x, 1)))
            };
            if i != 3 && i != 13 {
                shift += 2;
            }
            x = xn;
            y = yn.wrapping_shl((1 - (i == 3) as i32 - (i == 13) as i32) as u32);
        }
    }

    // 32 rotation iterations: drive z -> 0, (x, y) -> K*2^29*(cosh, sinh).
    let adj = repeat_adjusted(n);
    let mut sh_y = 2 * adj + 1;
    let mut sh_x = 1;
    let mut i = n;
    for _ in 0..32 {
        // Reachable i stays within 0..=40 (start_index <= 9 + 31).
        let mut t = *ATANH_TABLE.get_unchecked(i as usize);
        let z2 = if i == 3 || i == 13 {
            t = arm_asr(t, 1);
            z
        } else {
            z.wrapping_shl(1)
        };
        let dy = arm_asr(y, sh_y);
        let dx = arm_asr(x, sh_x);
        if z < 0 {
            x = x.wrapping_sub(dy);
            y = y.wrapping_sub(dx);
            z = z2.wrapping_add(t);
        } else {
            x = dy.wrapping_add(x);
            y = dx.wrapping_add(y);
            z = z2.wrapping_sub(t);
        }
        if i != 3 && i != 13 {
            sh_y += 1;
            sh_x += 1;
        }
        i += 1;
    }

    // Finale: inverse-gain multiplies; the sinh output's exponent field
    // is decremented by adj + 1 in raw bits (the seed loop's left-shift
    // debt), exactly as the original's sub/sub on the float pattern.
    let sinh_raw = __fmul(__i2f(y), SINH_SCALE);
    *out_sinh = sinh_raw
        .wrapping_sub((adj as u32) << 23)
        .wrapping_sub(0x0080_0000);
    *out_cosh = __fmul(__i2f(x), COSH_SCALE);
    *out_result = __fmul(__i2f(x.wrapping_add(arm_asr(y, adj))), COSH_SCALE);
}

