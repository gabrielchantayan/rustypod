//! Ports of the ARM ADS 1.0.1 fixed-point hyperbolic-CORDIC libm kernels:
//!
//! - `log_atanh_kernel` — original: `FUN_08035b3c` @ 0x08035b3c (524 bytes).
//! - `exp_frac_kernel`  — original: `FUN_08035d50` @ 0x08035d50 (696 bytes).
//!
//! Both are digit-recurrence (CORDIC) engines over the SAME 42-word
//! Q30 atanh(2^-i) table, run for exactly 32 iterations with the classic
//! hyperbolic-convergence repeats at iterations 3 and 13 (where the
//! shift counters do not advance). All shifts follow ARM register-shift
//! semantics (low 8 bits; >= 32 fills with the sign bit) — the loop
//! counters push the shifts well past 31, so this is load-bearing.
//!
//! Data tables, extracted byte-exact from work/firmware/osos.dec
//! (file offset = load address - 0x08000000):
//! - [`ATANH_TABLE`]     @ 0x08986264 (log copy) and 0x0898642c (exp
//!   copy) — the two 168-byte blocks are byte-identical (verified), so
//!   one const serves both kernels.
//! - [`LOG_SEED_TABLE`]  @ 0x0898630c — 9 x 32-byte range-reduction rows
//!   for the log kernel (literal @ 0x08035d48 + pc @ 0x08035b90).
//! - [`EXP_SEED_TABLE`]  @ 0x089864d4 — 12 x 8-byte seed pairs for the
//!   exp kernel, indexed by -exponent-1 (literal @ 0x08036008 + pc
//!   @ 0x08035dc0, walked backwards).
//!
//! `log_atanh_kernel` (vectoring mode, sole caller `log_decompose`
//! @ 0x080340fc through the `LOG_ATANH_KERNEL` hook): computes
//! atanh(u) = ln(m) for the reduced u = (m^2-1)/(m^2+1), u a float bit
//! pattern in (2^-12, 0.6). Inputs <= 0x39800000 (2^-12, signed compare)
//! return unchanged. The seed row search (row 8 down to row 0; row 0
//! matches any u < 1, row 8 is unreachable because its exponent -14 is
//! below the domain floor) pre-rotates the state to
//! (x, y) ~ (A + u*B*2^-S, u*A + B*2^-S) in Q29 via 64-bit products
//! (`smull` + `__aeabi_lasr`), seeds the Q(30+scale-1) accumulator, then
//! 32 vectoring iterations drive y -> 0 while the accumulator gathers
//! signed atanh table terms. Result: `__fdiv(__i2f(acc),
//! __fscalb(__i2f(1 << (result_scale - 1)), 30))`.
//!
//! `exp_frac_kernel` (rotation mode, sole caller `expf_core`
//! @ 0x08033f40, call site 0x08033fdc, through the `EXP_FRAC_KERNEL`
//! hook): for frac a float bit pattern, writes sinh(frac) to
//! `*out_sinh`, cosh(frac) to `*out_cosh` and e^frac to `*out_result`
//! (the only output the caller reads). Inputs <= 0x39800000 short-cut to
//! (frac, 1.0f, `__fadd(frac, 1.0f)`). Otherwise the seed pair for the
//! exponent subtracts a running atanh sum from the Q29 mantissa to form
//! the residual angle z, a seed loop of `start_index` fixed rotations
//! rebuilds the matching (x, y), and 32 rotation iterations drive
//! z -> 0, converging (x, y) -> K*2^29*(cosh, sinh). The finale
//! multiplies by the inverse-gain constants 1/K * 2^-28 @ 0x08036010
//! (sinh) and 1/K * 2^-29 @ 0x08036014 (cosh, result), and rescales the
//! sinh output by subtracting `(adj + 1) << 23` from its exponent field
//! directly (adj = seed-loop left-shift debt).
//!
//! Deviations (behavior-preserving):
//! - The original stores the un-rescaled sinh product to `*out_sinh` and
//!   immediately overwrites it (str/sub/sub/str @ 0x08035fb8-0x08035fc4);
//!   only the final value is stored here.
//! - The original returns leftover registers (the popped frac/out_sinh
//!   pair); the caller ignores them, so the port returns nothing.
//! - The exponent >= 0 branch of `exp_frac_kernel` (frac >= 1.0) is
//!   unreachable from the sole caller (frac = x - floor(x) in [0, 1))
//!   but fully ported and pinned by tests.
//!
//! Every pinned test vector was generated by an independent Python
//! transcription of the disassembly (not this Rust) driving the
//! byte-exact tables. Measured accuracy vs the host libm across the
//! caller domains: atanh within 1 ulp; e^frac and cosh within 2 ulp,
//! sinh within 3 ulp (the sinh path rounds three times: __i2f, __fmul,
//! then the raw exponent-field rescale).

