/// standard_cipher_table_three_lookup — original: `FUN_0802de90` @
/// `0x0802de90` (12 bytes, `0x0802de90..0x0802de9c`, 14 plain `bl` call
/// sites, no predicated calls).
///
/// Loads the base address `0x0891f24c`, then returns the byte at the raw r0
/// offset. The 14 verified callers all pass a byte value; the raw ARM code
/// deliberately has no bounds or null guard.
///
/// Deviations: none. The unchecked indexing preserves the original's
/// unguarded access for its valid-byte caller contract.
///
/// # Safety
/// `index` must be less than 256. As on retailOS, another value reads outside
/// the lookup table rather than being validated.
#[cfg_attr(target_os = "none", no_mangle)]
#[inline(never)]
pub unsafe extern "C" fn standard_cipher_table_three_lookup(index: u32) -> u8 {
    *STANDARD_CIPHER_TABLE_THREE.get_unchecked(index as usize)
}

#[cfg(test)]
mod tests {
    use super::standard_cipher_table_three_lookup;

    #[test]
    fn returns_verified_bytes_at_table_boundaries_and_middle() {
        let cases = [
            (0x00, 0xf4), (0x01, 0x65), (0x0f, 0xf2), (0x10, 0xe9),
            (0x7f, 0x50), (0x80, 0x69), (0xfe, 0x5b), (0xff, 0x50),
        ];

        for (index, expected) in cases {
            assert_eq!(unsafe { standard_cipher_table_three_lookup(index) }, expected,
                "table byte at {index:#04x}");
        }
    }
}
