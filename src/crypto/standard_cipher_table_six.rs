/// standard_cipher_table_six_lookup — original: `FUN_0802deb4` @
/// `0x0802deb4` (12 bytes, `0x0802deb4..0x0802dec0`, 14 plain `bl` call
/// sites, no predicated calls).
///
/// Loads the base address `0x0891f54c`, then returns the byte at the raw r0
/// offset. The 14 verified callers all pass a byte value; the raw ARM code
/// deliberately has no bounds or null guard.
///
/// Deviations: none. The unchecked indexing preserves the original's
/// unguarded access for its valid-byte caller contract.
///
/// # Safety
/// `index` must be less than 256. As on retailOS, another value reads outside
/// the lookup table rather than being validated.
#[cfg_attr(target_os = "none", no_mangle)]
#[inline(never)]
pub unsafe extern "C" fn standard_cipher_table_six_lookup(index: u32) -> u8 {
    *STANDARD_CIPHER_TABLE_SIX.get_unchecked(index as usize)
}

#[cfg(test)]
mod tests {
    use super::standard_cipher_table_six_lookup;

    #[test]
    fn returns_verified_bytes_at_table_boundaries_and_middle() {
        let cases = [
            (0x00, 0xdd), (0x01, 0x75), (0x0f, 0x61), (0x10, 0xf2),
            (0x7f, 0xef), (0x80, 0xf3), (0xfe, 0xeb), (0xff, 0xe8),
        ];

        for (index, expected) in cases {
            assert_eq!(unsafe { standard_cipher_table_six_lookup(index) }, expected,
                "table byte at {index:#04x}");
        }
    }
}
