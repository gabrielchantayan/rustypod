/// standard_cipher_table_four_lookup — original: `FUN_0802de9c` @
/// `0x0802de9c` (12 bytes, `0x0802de9c..0x0802dea8`, 14 plain `bl` call
/// sites, no predicated calls).
///
/// Loads the base address `0x0891f34c`, then returns the byte at the raw r0
/// offset. The 14 verified callers all pass a byte value; the raw ARM code
/// deliberately has no bounds or null guard.
///
/// Deviations: none. The unchecked indexing preserves the original's
/// unguarded access for its valid-byte caller contract.
///
/// # Safety
/// `index` must be less than 256. As on retailOS, another value reads outside
/// the lookup table rather than being validated.
#[cfg_attr(target_os = "none", no_mangle)]
#[inline(never)]
pub unsafe extern "C" fn standard_cipher_table_four_lookup(index: u32) -> u8 {
    *STANDARD_CIPHER_TABLE_FOUR.get_unchecked(index as usize)
}

#[cfg(test)]
mod tests {
    use super::standard_cipher_table_four_lookup;

    #[test]
    fn returns_verified_bytes_at_table_boundaries_and_middle() {
        let cases = [
            (0x00, 0xe9), (0x01, 0x50), (0x0f, 0xe5), (0x10, 0xf2),
            (0x7f, 0xe1), (0x80, 0xec), (0xfe, 0xf2), (0xff, 0x74),
        ];

        for (index, expected) in cases {
            assert_eq!(unsafe { standard_cipher_table_four_lookup(index) }, expected,
                "table byte at {index:#04x}");
        }
    }
}
