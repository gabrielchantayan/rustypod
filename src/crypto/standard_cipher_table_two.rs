/// standard_cipher_table_two_lookup — original: `FUN_0802de84` @
/// `0x0802de84` (12 bytes, `0x0802de84..0x0802de90`, 10 plain `bl` call
/// sites, no predicated calls).
///
/// Loads the base address `0x0891f14c`, then returns the byte at the raw r0
/// offset. The 10 verified callers all pass a byte value; the raw ARM code
/// deliberately has no bounds or null guard.
///
/// Deviations: none. The unchecked indexing preserves the original's
/// unguarded valid-byte caller contract.
///
/// # Safety
///
/// `index` must be less than 256. As on retailOS, another value reads outside
/// the lookup table rather than being validated.
#[cfg_attr(target_os = "none", no_mangle)]
#[inline(never)]
pub unsafe extern "C" fn standard_cipher_table_two_lookup(index: u32) -> u8 {
    *STANDARD_CIPHER_TABLE_TWO.get_unchecked(index as usize)
}

#[cfg(test)]
mod tests {
    use super::standard_cipher_table_two_lookup;

    #[test]
    fn returns_verified_bytes_at_table_boundaries_and_middle() {
        let cases = [
            (0x00, 0x80), (0x01, 0x24), (0x0f, 0x80), (0x10, 0x21),
            (0x7f, 0x6c), (0x80, 0x03), (0xfe, 0xe3), (0xff, 0xf5),
        ];

        for (index, expected) in cases {
            assert_eq!(unsafe { standard_cipher_table_two_lookup(index) }, expected,
                "table byte at {index:#04x}");
        }
    }
}
