//! `0x0802de78..0x0802de84`; the next sibling starts at `0x0802de84`). A
//! complete decoded ARM B/BL-word scan of `osos.dec` finds ten direct call
//! sites, all unconditional `bl` instructions.
//!
//! # Algorithm
//!
//! Loads the byte at the raw `r0` offset of the 256-byte table at
//! `0x0891f04c`. Callers provide byte-range inputs while constructing the
//! proprietary STANDARD cipher's table-driven transforms. The raw ARM code
//! deliberately has no bounds or NULL guard.
//!
//! # Deliberate deviation
//!
