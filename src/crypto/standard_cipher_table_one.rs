/// Returns a byte from the first STANDARD cipher lookup table.
///
/// # Safety
///
/// `index` must be less than 256. As on retailOS, another value reads outside
/// the lookup table rather than being validated.
#[cfg_attr(target_os = "none", no_mangle)]
#[inline(never)]
pub unsafe extern "C" fn standard_cipher_table_one_lookup(index: u32) -> u8 {
    *STANDARD_CIPHER_TABLE_ONE.get_unchecked(index as usize)
}

#[cfg(test)]
mod tests {
    use super::standard_cipher_table_one_lookup;

    #[test]
    fn returns_verified_bytes_at_table_boundaries_and_middle() {
        let cases = [
            (0x00, 0x4e), (0x01, 0xb8), (0x0f, 0xe2), (0x10, 0xe9),
            (0x7f, 0x69), (0x80, 0x80), (0xfe, 0xef), (0xff, 0x64),
        ];

        for (index, expected) in cases {
            assert_eq!(unsafe { standard_cipher_table_one_lookup(index) }, expected,
                "table byte at {index:#04x}");
        }
    }
}
