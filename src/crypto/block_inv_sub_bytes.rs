/// Substitute exactly sixteen writable bytes; byte alignment is unrestricted.
///
/// # Safety
/// `state` must point to sixteen initialized, writable bytes of ordinary RAM.
#[cfg_attr(target_os = "none", no_mangle)]
#[inline(never)]
pub unsafe extern "C" fn block_inv_sub_bytes(state: *mut u8) {
    for word in 0..4 {
        for byte in 0..4 {
            let p = state.add(word * 4 + byte);
            *p = BLOCK_INV_SUB_TABLE[*p as usize];
        }
    }
}

#[cfg(test)]
mod tests {
    use super::block_inv_sub_bytes;

    #[test]
    fn raw_table_vector_at_every_byte_alignment_preserves_neighbors() {
        let input = [0x00, 0x01, 0x02, 0x0e, 0x10, 0x1f, 0x20, 0x3f,
                     0x40, 0x7f, 0x80, 0x9f, 0xa0, 0xbf, 0xfe, 0xff];
        // Independently decoded bytes from osos.dec at 0x0891ef4c + input.
        let expected = [0xe8, 0xef, 0xef, 0xec, 0x65, 0x04, 0x4d, 0x80,
                        0x00, 0xf9, 0xf2, 0x8f, 0x68, 0x1d, 0x4e, 0x96];
        for offset in 1..=4 {
            let mut storage = [0xa5; 24];
            storage[offset..offset + 16].copy_from_slice(&input);
            unsafe { block_inv_sub_bytes(storage.as_mut_ptr().add(offset)) };
            assert_eq!(&storage[offset..offset + 16], &expected);
            assert!(storage[..offset].iter().all(|&b| b == 0xa5));
            assert!(storage[offset + 16..].iter().all(|&b| b == 0xa5));
        }
    }

    #[test]
    fn repeated_substitution_uses_current_state_not_original_indices() {
        let mut state = [0u8; 16];
        unsafe { block_inv_sub_bytes(state.as_mut_ptr()) };
        assert_eq!(state, [0xe8; 16]);
        unsafe { block_inv_sub_bytes(state.as_mut_ptr()) };
        assert_eq!(state, [0x31; 16]);
    }
}
