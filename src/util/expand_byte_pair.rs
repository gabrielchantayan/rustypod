#[cfg(test)]
mod tests {
    extern crate std;

    use super::{expand_byte_pair, BYTE_CODEWORD_TABLE};

    /// Independent model: codeword for byte b is table[b] | table[0x100+b]<<8,
    /// written little-endian; the function returns 0.
    fn reference(src: [u8; 2]) -> [u8; 4] {
        let mut out = [0u8; 4];
        for (i, b) in src.iter().enumerate() {
            let codeword = BYTE_CODEWORD_TABLE[*b as usize] as u16
                | (BYTE_CODEWORD_TABLE[0x100 + *b as usize] as u16) << 8;
            out[2 * i..2 * i + 2].copy_from_slice(&codeword.to_le_bytes());
        }
        out
    }

    #[test]
    fn returns_zero_and_writes_exactly_four_bytes() {
        let src = [0x39, 0xa4];
        let mut dst = [0xff; 6];
        let ret = unsafe { expand_byte_pair(src.as_ptr(), dst.as_mut_ptr().add(1)) };
        assert_eq!(ret, 0);
        assert_eq!(&dst[1..5], &reference(src));
        assert_eq!(dst[0], 0xff, "byte before dst untouched");
        assert_eq!(dst[5], 0xff, "byte after dst untouched");
    }

    #[test]
    fn matches_reference_for_all_byte_pairs() {
        for a in 0..=0xffu8 {
            for b in [0x00u8, 0x01, 0x7f, 0x80, 0xfe, 0xff, a.wrapping_add(1)] {
                let src = [a, b];
                let mut dst = [0u8; 4];
                let ret = unsafe { expand_byte_pair(src.as_ptr(), dst.as_mut_ptr()) };
                assert_eq!(dst, reference(src), "src={src:02x?}");
                assert_eq!(ret, 0);
            }
        }
    }

    #[test]
    fn table_matches_firmware_bytes() {
        // Anchors from osos.dec @ 0x083f4e84.
        assert_eq!(&BYTE_CODEWORD_TABLE[..4], &[0x18, 0x00, 0x00, 0x00]);
        assert_eq!(&BYTE_CODEWORD_TABLE[0x100..0x104], &[0x58, 0x00, 0x9a, 0x00]);
        assert_eq!(BYTE_CODEWORD_TABLE.len(), 0x200);
    }
}
