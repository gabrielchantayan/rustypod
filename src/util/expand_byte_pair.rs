//! Byte-pair codeword expansion via a 256-entry 16-bit lookup table.

/// expand_byte_pair — original: `FUN_08398cdc` @ **0x08398cdc** (**64
/// bytes exactly**, `0x08398cdc..0x08398d1c`; the literal pool word at
/// `0x08398d1c` holds the table pointer and the next separately linked
/// function begins at `0x08398d20`).
///
/// Decoding every ARM B/BL word in `osos.dec` verifies **4 direct inbound
/// `bl` call sites**, all unconditional (`0x080436a8`, `0x080436bc`,
/// `0x080436c8`, `0x080436d4`, all inside `FUN_080435f0`); there are no
/// predicated BL forms or direct tail branches.
///
/// The body maps each of the two source bytes to a 16-bit codeword through
/// a 256-entry table held as two 256-byte halves at `0x083f4e84`: the low
/// half at `+0x000` and the high half at `+0x100`. It stores
/// `table_lo[src[0]]`, `table_hi[src[0]]`, `table_lo[src[1]]`,
/// `table_hi[src[1]]` to `dst[0..4]` — i.e. two little-endian u16 codewords
/// — and returns 0. All four loads use `ldrb` and all four stores `strb`;
/// `dst` is never read, so overlapping ranges behave like a plain
/// four-byte write.
///
/// Deliberate deviations: the original dereferences its literal-pool table
/// pointer to read the table in place at `0x083f4e84`; the port embeds a
/// byte-identical copy (`BYTE_CODEWORD_TABLE`) since the data is read-only.
///
/// # Safety
/// `src` must be valid for two `u8` reads and `dst` for four `u8` writes.
#[cfg_attr(target_os = "none", no_mangle)]
#[inline(never)]
pub unsafe extern "C" fn expand_byte_pair(src: *const u8, dst: *mut u8) -> i32 {
    let first = src.read() as usize;
    dst.write(BYTE_CODEWORD_TABLE[first]);
    dst.add(1).write(BYTE_CODEWORD_TABLE[0x100 + first]);
    let second = src.add(1).read() as usize;
    dst.add(2).write(BYTE_CODEWORD_TABLE[second]);
    dst.add(3).write(BYTE_CODEWORD_TABLE[0x100 + second]);
    0
}

